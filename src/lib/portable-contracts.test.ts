import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { evaluatePortableContract, PORTABLE_OPERATIONS } from "./portable-contracts-adapter";

const root = new URL("../../contracts/v1/", import.meta.url);
const manifest = JSON.parse(readFileSync(new URL("manifest.json", root), "utf8")) as { contractVersion: number; suites: string[]; operations: Record<string, unknown> };
const ids = new Set<string>();
const operations = new Set<string>();
for (const name of manifest.suites) {
  const suite = JSON.parse(readFileSync(new URL(name, root), "utf8")) as { contractVersion: number; cases: Array<{ id: string; operation: string; input: unknown; expected: unknown }> };
  assert.equal(suite.contractVersion, 1);
  for (const vector of suite.cases) {
    assert(!ids.has(vector.id), `Duplicate portable vector ${vector.id}`);
    assert(Object.hasOwn(vector, "expected"), `Missing fixed expected output ${vector.id}`);
    ids.add(vector.id); operations.add(vector.operation);
    test(`portable v1: ${vector.id}`, () => {
      // JSON semantics remove optional undefined fields; no expected values are generated by the implementation.
      const actual = JSON.parse(JSON.stringify(evaluatePortableContract(vector.operation, structuredClone(vector.input))));
      assert.deepEqual(actual, vector.expected);
    });
  }
}
test("portable manifest covers every adapter operation with unique fixed vectors", () => {
  assert.equal(manifest.contractVersion, 1);
  assert.deepEqual([...operations].sort(), [...PORTABLE_OPERATIONS].sort());
  assert.deepEqual(Object.keys(manifest.operations).sort(), [...PORTABLE_OPERATIONS].sort());
});
